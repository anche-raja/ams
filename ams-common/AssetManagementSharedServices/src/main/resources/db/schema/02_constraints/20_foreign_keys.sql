  FOREIGN KEY (SHIP_WINDOW_ID) REFERENCES AMS_TIMESLOTS (TIMESLOT_ID);

-- MAINT_WINDOW_ID and CONFIG_ID are deliberately left unconstrained in the other direction:
-- AMS_MAINTENANCE_WINDOWS.ORDER_ID and AMS_ASSET_CONFIGS.ORDER_ID already point back here, and
-- adding the reverse key as well would make the pair mutually dependent and unsavable in one pass.
ALTER TABLE AMS_MAINTENANCE_WINDOWS ADD CONSTRAINT IF NOT EXISTS MAINTWIN_ORDER_FK
  FOREIGN KEY (ORDER_ID) REFERENCES AMS_ORDERS (ORDER_ID);
ALTER TABLE AMS_ASSET_CONFIGS ADD CONSTRAINT IF NOT EXISTS ASSETCFG_ORDER_FK
  FOREIGN KEY (ORDER_ID) REFERENCES AMS_ORDERS (ORDER_ID);
