  FOREIGN KEY (ORDER_CONTACT_ID) REFERENCES AMS_CONTACTS (CONTACT_ID);
ALTER TABLE AMS_ORDERS ADD CONSTRAINT IF NOT EXISTS ORDERS_SHIP_CONTACT_FK
  FOREIGN KEY (SHIP_CONTACT_ID) REFERENCES AMS_CONTACTS (CONTACT_ID);
ALTER TABLE AMS_ORDERS ADD CONSTRAINT IF NOT EXISTS ORDERS_INSTALL_CONTACT_FK
  FOREIGN KEY (INSTALL_CONTACT_ID) REFERENCES AMS_CONTACTS (CONTACT_ID);
