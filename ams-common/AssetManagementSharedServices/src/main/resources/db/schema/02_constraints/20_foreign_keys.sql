-- The ordering flow's captured data.
--
-- All nullable on the child side: the steps are completed one screen at a time and a
-- saved-for-later order is a partly populated one, so an order row legitimately exists with any
-- subset of these still unset.
ALTER TABLE AMS_SUBSCRIBER_PCS ADD CONSTRAINT IF NOT EXISTS SUBPC_ORDER_FK
  FOREIGN KEY (ORDER_ID) REFERENCES AMS_ORDERS (ORDER_ID);

ALTER TABLE AMS_ORDERS ADD CONSTRAINT IF NOT EXISTS ORDERS_SHIP_ADDR_FK
  FOREIGN KEY (SHIP_ADDRESS_ID) REFERENCES AMS_ADDRESSES (ADDRESS_ID);
