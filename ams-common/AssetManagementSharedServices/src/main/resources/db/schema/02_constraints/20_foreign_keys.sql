-- Foreign keys, selectively.
--
-- Added only where the parent is unambiguous. Deliberately NOT added to AMS_EVENTS.ENTITY_ID or
-- AMS_EMAIL_QUEUE.ENTITY_ID: those columns are polymorphic across five entity types (order, asset,
-- NCR, RMA, decommission), so there is no single table to point at and no constraint that could
-- express it. The check constraints in 10_check_constraints.sql carry the rest of the integrity.
--
-- Every one of these is nullable on the child side, which matters: a new-install order has no
-- asset yet, and OrderDAOImpl.insertOrder binds NULL for ASSET_ID in that case.

ALTER TABLE AMS_ASSETS ADD CONSTRAINT IF NOT EXISTS ASSETS_CUSTOMER_FK
  FOREIGN KEY (CUSTOMER_ID) REFERENCES AMS_CUSTOMERS (CUSTOMER_ID);

ALTER TABLE AMS_CONTACTS ADD CONSTRAINT IF NOT EXISTS CONTACTS_CUSTOMER_FK
  FOREIGN KEY (CUSTOMER_ID) REFERENCES AMS_CUSTOMERS (CUSTOMER_ID);

ALTER TABLE AMS_SERVICES ADD CONSTRAINT IF NOT EXISTS SERVICES_CUSTOMER_FK
  FOREIGN KEY (CUSTOMER_ID) REFERENCES AMS_CUSTOMERS (CUSTOMER_ID);

ALTER TABLE AMS_CUSTOMER_EARLY_ADOPTERS ADD CONSTRAINT IF NOT EXISTS CUSTEA_CUSTOMER_FK
  FOREIGN KEY (CUSTOMER_ID) REFERENCES AMS_CUSTOMERS (CUSTOMER_ID);

ALTER TABLE AMS_ORDERS ADD CONSTRAINT IF NOT EXISTS ORDERS_CUSTOMER_FK
  FOREIGN KEY (CUSTOMER_ID) REFERENCES AMS_CUSTOMERS (CUSTOMER_ID);
ALTER TABLE AMS_ORDERS ADD CONSTRAINT IF NOT EXISTS ORDERS_ASSET_FK
  FOREIGN KEY (ASSET_ID) REFERENCES AMS_ASSETS (ASSET_ID);

ALTER TABLE AMS_ASSET_CONFIGS ADD CONSTRAINT IF NOT EXISTS ASSETCFG_ASSET_FK
  FOREIGN KEY (ASSET_ID) REFERENCES AMS_ASSETS (ASSET_ID);

ALTER TABLE AMS_PORT_CONFIGS ADD CONSTRAINT IF NOT EXISTS PORTCFG_CONFIG_FK
  FOREIGN KEY (CONFIG_ID) REFERENCES AMS_ASSET_CONFIGS (CONFIG_ID);

ALTER TABLE AMS_DECOMMISSIONS ADD CONSTRAINT IF NOT EXISTS DECOM_ASSET_FK
  FOREIGN KEY (ASSET_ID) REFERENCES AMS_ASSETS (ASSET_ID);

ALTER TABLE AMS_ASSET_RETURNS ADD CONSTRAINT IF NOT EXISTS ASSETRET_ASSET_FK
  FOREIGN KEY (ASSET_ID) REFERENCES AMS_ASSETS (ASSET_ID);

ALTER TABLE AMS_RMAS ADD CONSTRAINT IF NOT EXISTS RMAS_ASSET_FK
  FOREIGN KEY (ASSET_ID) REFERENCES AMS_ASSETS (ASSET_ID);

ALTER TABLE AMS_MAINTENANCE_WINDOWS ADD CONSTRAINT IF NOT EXISTS MAINTWIN_ASSET_FK
  FOREIGN KEY (ASSET_ID) REFERENCES AMS_ASSETS (ASSET_ID);

ALTER TABLE AMS_NETWORK_CHANGE_REQUESTS ADD CONSTRAINT IF NOT EXISTS NCR_CUSTOMER_FK
  FOREIGN KEY (CUSTOMER_ID) REFERENCES AMS_CUSTOMERS (CUSTOMER_ID);
ALTER TABLE AMS_NETWORK_CHANGE_REQUESTS ADD CONSTRAINT IF NOT EXISTS NCR_ASSET_FK
  FOREIGN KEY (ASSET_ID) REFERENCES AMS_ASSETS (ASSET_ID);

-- A child table proper: an NCR type row is meaningless without its request.
ALTER TABLE AMS_NCR_TYPES ADD CONSTRAINT IF NOT EXISTS NCRTYPES_NCR_FK
  FOREIGN KEY (NCR_ID) REFERENCES AMS_NETWORK_CHANGE_REQUESTS (NCR_ID) ON DELETE CASCADE;

ALTER TABLE AMS_CUSTOMER_SCHEDULES ADD CONSTRAINT IF NOT EXISTS CUSTSCHED_CUSTOMER_FK
