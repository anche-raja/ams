-- Shipping windows are generated relative to SYSDATE by 07_seed/36, so unlike every other seed
-- row they can be seeded and still be useless: a generator that produced only past dates would
-- leave the last step of the ordering flow permanently empty with nothing to show it had failed.
--
-- What is asserted is that bookable future windows EXIST - not that none have aged into the past.
-- An earlier version failed the gate on any past window, which is right for the few minutes after a
-- fresh build and wrong every day after: windows age out by design, and on a database that has been
-- up a fortnight most of them have. That check turned an ordinary healthy schema into a hard
-- failure, so it is gone; the future count is the thing that actually decides whether the screen
-- has anything on it.
DECLARE
  l_future NUMBER;
  l_past   NUMBER;
BEGIN
  SELECT COUNT(*) INTO l_future
    FROM AMS_TIMESLOTS
   WHERE CALL_TYPE_CD = 'SHIP' AND START_TM > SYSTIMESTAMP AND AVAILABLE_FL = 'Y';
  SELECT COUNT(*) INTO l_past
    FROM AMS_TIMESLOTS
   WHERE CALL_TYPE_CD = 'SHIP' AND START_TM <= SYSTIMESTAMP;

  IF l_future = 0 THEN
    RAISE_APPLICATION_ERROR(-20006,
      'VALIDATION FAILED: no bookable shipping windows in the future'
      || ' (' || l_past || ' have aged into the past - re-run 07_seed/36 to roll them forward)');
  END IF;
  DBMS_OUTPUT.PUT_LINE('  ok   bookable shipping windows                 ' || l_future
                       || CASE WHEN l_past > 0 THEN '  (' || l_past || ' aged out)' ELSE '' END);
END;
/

-- The same failure mode as above, for the installation and tech-line capacity generated by
-- 07_seed/37. Those two calendars are what the second half of the lifecycle runs on: with no
-- future slots an order can be placed but never scheduled, and the screen gives no hint why.
-- The fixed September 2025 slots from 07_seed/14 are deliberately left out of this - they are
-- past by design and exist for the DAO tests, so only the generated future ones are counted.
DECLARE
  l_install  NUMBER;
  l_techline NUMBER;
BEGIN
  SELECT COUNT(*) INTO l_install
    FROM AMS_TIMESLOTS
   WHERE CALL_TYPE_CD = 'INSTALL' AND START_TM > SYSTIMESTAMP AND AVAILABLE_FL = 'Y';
  SELECT COUNT(*) INTO l_techline
    FROM AMS_TIMESLOTS
   WHERE CALL_TYPE_CD = 'TECHLINE' AND START_TM > SYSTIMESTAMP AND AVAILABLE_FL = 'Y';

  IF l_install = 0 THEN
    RAISE_APPLICATION_ERROR(-20007,
      'VALIDATION FAILED: no bookable installation windows in the future');
  END IF;
  IF l_techline = 0 THEN
    RAISE_APPLICATION_ERROR(-20007,
      'VALIDATION FAILED: no bookable tech-line windows in the future');
  END IF;
  DBMS_OUTPUT.PUT_LINE('  ok   bookable installation windows             ' || l_install);
  DBMS_OUTPUT.PUT_LINE('  ok   bookable tech-line windows                ' || l_techline);
END;
