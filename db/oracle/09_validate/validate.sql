DECLARE
  l_status    VARCHAR2(30);
  l_message   VARCHAR2(400);
  l_window_id NUMBER;
  l_released  NUMBER;
  l_email_id  NUMBER;
  l_reserved  NUMBER;
  l_decom_id  NUMBER;
  l_when      TIMESTAMP := CAST(TRUNC(SYSDATE) + 7 AS TIMESTAMP);

  PROCEDURE assert_status(p_what IN VARCHAR2, p_expected IN VARCHAR2, p_actual IN VARCHAR2) IS
  BEGIN
    IF NVL(p_actual, '<null>') <> p_expected THEN
      RAISE_APPLICATION_ERROR(-20002,
        'VALIDATION FAILED: ' || p_what || ' expected ' || p_expected
        || ', got ' || NVL(p_actual, '<null>'));
    END IF;
    DBMS_OUTPUT.PUT_LINE('  ok   ' || RPAD(p_what, 44) || p_actual);
  END assert_status;
BEGIN
  DBMS_OUTPUT.PUT_LINE('--- AMS_SCHEDULING_PG ---');

  -- Timeslot 9702 is seeded capacity 2 / reserved 2. The race a mock cannot reproduce.
  AMS_SCHEDULING_PG.reserve_timeslot(9702, 777001, 'TECHLINE', l_when, 'validate',
                                     l_status, l_message);
  assert_status('reserve_timeslot on a full slot', 'NO_CAPACITY', l_status);

  -- 9701 is capacity 4 / reserved 1.
  AMS_SCHEDULING_PG.reserve_timeslot(9701, 777001, 'TECHLINE', l_when, 'validate',
                                     l_status, l_message);
  assert_status('reserve_timeslot with room', 'OK', l_status);

  SELECT RESERVED_COUNT INTO l_reserved FROM AMS_TIMESLOTS WHERE TIMESLOT_ID = 9701;
  IF l_reserved <> 2 THEN
    RAISE_APPLICATION_ERROR(-20003, 'RESERVED_COUNT should be 2, is ' || l_reserved);
  END IF;
  DBMS_OUTPUT.PUT_LINE('  ok   reserved count incremented to ' || l_reserved);

  -- Reserving again must not take a second place: a double-clicked form is not an error.
  AMS_SCHEDULING_PG.reserve_timeslot(9701, 777001, 'TECHLINE', l_when, 'validate',
                                     l_status, l_message);
  assert_status('reserve_timeslot repeated', 'OK', l_status);
  SELECT RESERVED_COUNT INTO l_reserved FROM AMS_TIMESLOTS WHERE TIMESLOT_ID = 9701;
  IF l_reserved <> 2 THEN
    RAISE_APPLICATION_ERROR(-20003, 'repeat reserve double-counted: ' || l_reserved);
  END IF;
  DBMS_OUTPUT.PUT_LINE('  ok   repeat reserve did not double-count');

  AMS_SCHEDULING_PG.cancel_timeslot(9701, 777001, 'TECHLINE', 'validate', l_status);
  assert_status('cancel_timeslot', 'OK', l_status);

  -- The whole reason AMS_TIMESLOT_RESERVATIONS exists: a second cancel must be harmless.
  AMS_SCHEDULING_PG.cancel_timeslot(9701, 777001, 'TECHLINE', 'validate', l_status);
  assert_status('cancel_timeslot repeated', 'NOT_RESERVED', l_status);
  SELECT RESERVED_COUNT INTO l_reserved FROM AMS_TIMESLOTS WHERE TIMESLOT_ID = 9701;
  IF l_reserved <> 1 THEN
    RAISE_APPLICATION_ERROR(-20003, 'double cancel corrupted the count: ' || l_reserved);
  END IF;
  DBMS_OUTPUT.PUT_LINE('  ok   double cancel left the count at ' || l_reserved);

  AMS_SCHEDULING_PG.reserve_timeslot(9701, 777001, 'BOGUS', l_when, 'validate',
                                     l_status, l_message);
  assert_status('reserve_timeslot bad entity type', 'INVALID_INPUT', l_status);

  -- Asset 5001 is ACTIVE with no decommission, so this creates one (id passed as 0, the way
  -- CalendarServiceImpl passes a Java null).
  AMS_SCHEDULING_PG.schedule_decommission(0, 5001, l_when, 'Y', 'validate', l_status);
  assert_status('schedule_decommission', 'OK', l_status);

  AMS_SCHEDULING_PG.schedule_decommission(0, 5001,
    CAST(TRUNC(SYSDATE) + 400 AS TIMESTAMP), 'N', 'validate', l_status);
  assert_status('schedule_decommission beyond window', 'OUTSIDE_WINDOW', l_status);

  SELECT DECOMMISSION_ID INTO l_decom_id
    FROM AMS_DECOMMISSIONS WHERE ASSET_ID = 5001 AND DECOM_STATUS_CD = 'SCHEDULED';
  AMS_SCHEDULING_PG.cancel_decommission(l_decom_id, 'validation', 'validate', l_status);
  assert_status('cancel_decommission', 'OK', l_status);

  DBMS_OUTPUT.PUT_LINE('--- AMS_NCR_SCHEDULING_PG ---');

  -- 9002 is SCHEDULED (open); 9001 is COMPLETED.
  AMS_NCR_SCHEDULING_PG.schedule_ncr(9002, l_when, 'validate', l_status);
  assert_status('schedule_ncr', 'OK', l_status);

  AMS_NCR_SCHEDULING_PG.schedule_ncr(9001, l_when, 'validate', l_status);
  assert_status('schedule_ncr on a closed request', 'NOT_OPEN', l_status);

  -- Asset 5003 has no installation address, so this resolves to the 'ALL' circuit region.
  -- Site type deliberately null: CalendarServiceImpl passes null when the request has no proposed
  -- configuration, and that has to be a valid booking rather than an error.
  AMS_NCR_SCHEDULING_PG.schedule_site_type_ncr(9002, 5003, NULL, l_when, 'validate',
                                               l_status, l_window_id);
  assert_status('schedule_site_type_ncr, null site type', 'OK', l_status);
  IF l_window_id IS NULL THEN
    RAISE_APPLICATION_ERROR(-20004, 'schedule_site_type_ncr returned no circuit window id');
  END IF;
  DBMS_OUTPUT.PUT_LINE('  ok   circuit window id returned: ' || l_window_id);

  AMS_NCR_SCHEDULING_PG.schedule_site_type_ncr(9002, 5003, 'NOT_A_TYPE', l_when, 'validate',
                                               l_status, l_window_id);
  assert_status('schedule_site_type_ncr bad site type', 'INVALID_SITE_TYPE', l_status);

  AMS_NCR_SCHEDULING_PG.cancel_site_type_ncr(9002, 5003, 'validation', 'validate',
                                             l_status, l_released);
  assert_status('cancel_site_type_ncr', 'OK', l_status);
  IF l_released < 1 THEN
    RAISE_APPLICATION_ERROR(-20004, 'cancel_site_type_ncr released nothing');
  END IF;
  DBMS_OUTPUT.PUT_LINE('  ok   circuit windows released: ' || l_released);

  AMS_NCR_SCHEDULING_PG.cancel_ncr_date(9001, 'validation', 'validate', l_status);
  assert_status('cancel_ncr_date on a closed request', 'NOT_OPEN', l_status);

  DBMS_OUTPUT.PUT_LINE('--- AMS_EMAIL_PG ---');

  -- Order 6002 belongs to customer 1001, which has an ORDERING and an INSTALL contact.
  AMS_EMAIL_PG.add_entity_email('ORDER', 6002, 'ORDCONF', 'validate', l_status, l_email_id);
  assert_status('add_entity_email', 'OK', l_status);
  IF l_email_id IS NULL THEN
    RAISE_APPLICATION_ERROR(-20005, 'add_entity_email queued nothing');
  END IF;
  DBMS_OUTPUT.PUT_LINE('  ok   queued email id: ' || l_email_id);

  -- Immediately again: every recipient is now inside the de-duplication window.
  AMS_EMAIL_PG.add_entity_email('ORDER', 6002, 'ORDCONF', 'validate', l_status, l_email_id);
  assert_status('add_entity_email deduplicated', 'SUPPRESSED', l_status);

  AMS_EMAIL_PG.add_entity_email('NOPE', 6002, 'ORDCONF', 'validate', l_status, l_email_id);
  assert_status('add_entity_email bad entity type', 'INVALID_ENTITY_TYPE', l_status);

  AMS_EMAIL_PG.add_entity_email('ORDER', 999999, 'ORDCONF', 'validate', l_status, l_email_id);
  assert_status('add_entity_email unknown entity', 'NOT_FOUND', l_status);

  ROLLBACK;
  DBMS_OUTPUT.PUT_LINE('');
  DBMS_OUTPUT.PUT_LINE('AMS schema validated: all objects valid, all entry points callable.');
EXCEPTION
  WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
END;
