/*
 * Acceptance gate. Runs as the last step of 00_init.sh and fails the container if anything is
 * wrong, rather than letting a half-built schema come up "healthy".
 *
 * The smoke calls at the end matter more than they look. Spring's StoredProcedure binds parameters
 * positionally and RdbmsOperation.compile() never reads database metadata, so a procedure whose
 * signature does not match the Java compiles fine, deploys fine, starts fine - and throws
 * ORA-06550 the first time a user clicks the button. Nothing else in the build checks it. These
 * calls are that check.
 *
 * Everything here rolls back, so validation leaves no rows behind.
 */
SET SERVEROUTPUT ON SIZE UNLIMITED
SET FEEDBACK OFF

DECLARE
  l_errors    NUMBER;
  l_tables    NUMBER;
  l_sequences NUMBER;
  l_views     NUMBER;
  l_packages  NUMBER;
  l_bodies    NUMBER;
  l_invalid   NUMBER;

  PROCEDURE assert_equals(p_what IN VARCHAR2, p_expected IN NUMBER, p_actual IN NUMBER) IS
  BEGIN
    IF p_expected <> p_actual THEN
      RAISE_APPLICATION_ERROR(-20001,
        'VALIDATION FAILED: ' || p_what || ' expected ' || p_expected || ', found ' || p_actual);
    END IF;
    DBMS_OUTPUT.PUT_LINE('  ok   ' || RPAD(p_what, 28) || p_actual);
  END assert_equals;

  PROCEDURE assert_status(p_what IN VARCHAR2, p_expected IN VARCHAR2, p_actual IN VARCHAR2) IS
  BEGIN
    IF NVL(p_actual, '<null>') <> p_expected THEN
      RAISE_APPLICATION_ERROR(-20002,
        'VALIDATION FAILED: ' || p_what || ' expected status ' || p_expected
        || ', got ' || NVL(p_actual, '<null>'));
    END IF;
    DBMS_OUTPUT.PUT_LINE('  ok   ' || RPAD(p_what, 40) || p_actual);
  END assert_status;

BEGIN
  DBMS_OUTPUT.PUT_LINE('--- object counts ---');

  SELECT COUNT(*) INTO l_tables    FROM USER_TABLES;
  SELECT COUNT(*) INTO l_sequences FROM USER_SEQUENCES;
  SELECT COUNT(*) INTO l_views     FROM USER_VIEWS;
  SELECT COUNT(*) INTO l_packages  FROM USER_OBJECTS WHERE OBJECT_TYPE = 'PACKAGE';
  SELECT COUNT(*) INTO l_bodies    FROM USER_OBJECTS WHERE OBJECT_TYPE = 'PACKAGE BODY';

  assert_equals('tables',        35, l_tables);
  assert_equals('sequences',     19, l_sequences);
  assert_equals('views',          1, l_views);
  assert_equals('packages',       3, l_packages);
  assert_equals('package bodies', 3, l_bodies);

  -- An INVALID package body is the single most likely failure and is completely silent: SQL*Plus
  -- exits 0 after creating one.
  SELECT COUNT(*) INTO l_invalid FROM USER_OBJECTS WHERE STATUS <> 'VALID';
  IF l_invalid > 0 THEN
    DBMS_OUTPUT.PUT_LINE('--- invalid objects ---');
    FOR o IN (SELECT OBJECT_NAME, OBJECT_TYPE FROM USER_OBJECTS WHERE STATUS <> 'VALID') LOOP
      DBMS_OUTPUT.PUT_LINE('  ' || o.OBJECT_TYPE || ' ' || o.OBJECT_NAME);
    END LOOP;
  END IF;
  assert_equals('invalid objects', 0, l_invalid);

  SELECT COUNT(*) INTO l_errors FROM USER_ERRORS;
  IF l_errors > 0 THEN
    DBMS_OUTPUT.PUT_LINE('--- compilation errors ---');
    FOR e IN (SELECT NAME, LINE, POSITION, TEXT FROM USER_ERRORS ORDER BY NAME, SEQUENCE) LOOP
      DBMS_OUTPUT.PUT_LINE('  ' || e.NAME || ' ' || e.LINE || ':' || e.POSITION || ' ' || e.TEXT);
    END LOOP;
  END IF;
  assert_equals('compilation errors', 0, l_errors);
END;
